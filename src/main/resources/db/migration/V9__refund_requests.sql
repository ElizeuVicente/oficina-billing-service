CREATE TABLE refund_requests (
    saga_id UUID PRIMARY KEY,
    quote_id UUID NOT NULL,
    attempt_id UUID NOT NULL UNIQUE REFERENCES payment_attempts(attempt_id),
    provider_payment_id VARCHAR(20) NOT NULL,
    reason VARCHAR(80) NOT NULL,
    status VARCHAR(20) NOT NULL CHECK (status IN ('REQUESTED','DISPATCHING','SUBMITTED','UNKNOWN','CONFIRMED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
